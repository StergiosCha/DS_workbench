"""Add the maintained English nominal PP fragment to both native backends."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "src/dynamicsyntax/grammars"
MARKER = "// Nominal PP extensions. Generated by scripts/build_nominal_pp_extensions.py."


def build():
    for backend in ("mltt", "classical"):
        root = ROOT / f"2026-english-{backend}"
        cn, prop = ("CN", "Prop") if backend == "mltt" else ("cn", "t")
        lexical = f"""
nominal-pp(PRED)
IF Ty({backend}:{cn})
   ¬Ex.?x
THEN semantic-nominal-pp(PRED)
ELSE abort

bare-plural(NSORT)
IF ?Ty({backend}:{'object' if backend == 'mltt' else 'e'})
   ¬<\\/0>Ex.x
   ¬<\\/1>Ex.x
THEN put(Number(pl))
   make(\\/1)
   go(\\/1)
"""
        if backend == "mltt":
            lexical += r"""   put(Ty(mltt:arrow(CN,object)))
   put(Fo(mltt:lam(A,CN,sigma(x,A,top))))
   go(/\1)
   make(\/0)
   go(\/0)
   put(Ty(mltt:CN))
   put(Fo(mltt:NSORT))
ELSE abort
"""
        else:
            lexical += r"""   put(Ty(classical:arrow(cn,e)))
   put(Fo(classical:lam(P,cn,choice_eps(P))))
   put(!)
   go(/\1)
   make(\/0)
   go(\/0)
   put(?Ty(classical:cn))
   make(\/0)
   go(\/0)
   put(Ty(classical:e))
   freshput(T,entity)
   put(!)
   go(/\0)
   make(\/1)
   go(\/1)
   put(Ty(classical:arrow(e,cn)))
   put(Fo(classical:lam(x,e,cn(x,NSORT(x)))))
   put(!)
ELSE abort
"""
        computational = f"""
*nominal-pp-evaluation
IF [+NOMINAL-PP]
   ?[+NOMINAL-PP-CLOSED]
   Ty({backend}:{prop})
   ¬?Ty({backend}:{prop})
THEN semantic-nominal-pp-close
ELSE abort
"""
        lexicon = "\n".join(f"{word} nominal-pp {word}_nominal" for word in ("with", "in", "at", "on", "near"))
        lexicon += """
knife noun knife
eyewear noun eyewear
glasses bare-plural eyewear
runs intransitive run animal
run intransitive run animal
run intransitive-base run animal
"""
        for filename, addition in (("lexical-actions.txt", lexical),
                                   ("computational-actions.txt", computational),
                                   ("lexicon.txt", lexicon)):
            path = root / filename
            text = path.read_text().split(MARKER)[0].rstrip()
            if filename == "lexicon.txt":
                # General accompaniment includes humans and objects. Classical
                # e alone cannot enforce the old human-only companion sense.
                text = text.replace("with pp-modifier with_companion",
                                    "with pp-modifier with_accompaniment")
                text = text.replace("with pp-modifier-embedded with_companion",
                                    "with pp-modifier-embedded with_accompaniment")
            if filename == "computational-actions.txt":
                text = text.replace("   ¬[+REL]\n   ¬Ex.?x", "   ¬[+REL]\n   ¬[+NOMINAL-PP]\n   ¬Ex.?x")
            path.write_text(text + "\n\n" + MARKER + "\n" + addition.strip() + "\n")
        path = root / "semantics.json"
        theory = json.loads(path.read_text())
        for noun in ("knife", "eyewear"):
            theory["subtyping"][noun] = ["object"]
            if backend == "classical":
                theory["predicates"][noun] = ["object"]
        for word in ("with", "in", "at", "on", "near"):
            theory["predicates"][f"{word}_nominal"] = ["object", "object"]
        theory["predicates"]["with_accompaniment"] = ["object", "Prop"]
        theory["predicates"]["run"] = ["animal"]
        path.write_text(json.dumps(theory, indent=2, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    build()
