"""Maintain finite because/επειδή/διότι clauses in the four native grammars."""
import json
from pathlib import Path
from dylan.clause_inventory import CONNECTIVES, RELATIONS, templates

MARKER = "// Finite causal clauses. Generated by scripts/build_causal_extensions.py."
NOTE = "because(main, reason) relates two locally closed clause contents. It is an opaque causal relation, with no causal inference or truth axioms. Postposed reasons use LINK; preposed finite reasons require a comma and a main clause. Because-of nominals, nonfinite reasons, and unrestricted attachment/scope are not supplied."


def extend(root, backend, language):
    prop = "Prop" if backend == "mltt" else "t"
    content = "Content" if backend == "mltt" else "t"
    blocks = rf"""causal-post(UNUSED)
IF Ty({backend}:{prop})
THEN causal-post
ELSE abort

causal-front(UNUSED)
IF ?Ty({backend}:{prop})
THEN causal-front
ELSE abort

causal-boundary(UNUSED)
IF Tn(a)
THEN causal-boundary
ELSE abort
"""
    if backend == "mltt":
        blocks += rf"""
causal-post-content(UNUSED)
IF Ty({backend}:{content})
   [+CLAUSE]
THEN causal-post
ELSE abort
"""
    blocks += rf"""
clause-post(REL)
IF Ty({backend}:{prop})
THEN causal-post(REL)
ELSE abort

clause-front(REL)
IF ?Ty({backend}:{prop})
THEN causal-front(REL)
ELSE abort
"""
    if backend == "mltt":
        blocks += rf"""
clause-post-content(REL)
IF Ty({backend}:{content})
   [+CLAUSE]
THEN causal-post(REL)
ELSE abort
"""
    rows = [f"{word} {template} {relation}" for word, relations in CONNECTIVES[language].items()
            for relation in relations for template in templates(backend)]
    rows.append(", causal-boundary none")
    # These operators preserve a temporal contribution without pretending to
    # resolve a reference time or compute tense. Later/earlier are distinct
    # from late/early; they are never discarded as semantically empty words.
    temporal = ({"later": "later", "earlier": "earlier", "late": "late", "early": "early",
                 "today": "today", "yesterday": "yesterday", "tomorrow": "tomorrow", "soon": "soon"}
                if language == "en" else {"αργότερα": "later", "νωρίτερα": "earlier", "αργά": "late",
                 "νωρίς": "early", "σήμερα": "today", "χθες": "yesterday", "αύριο": "tomorrow", "σύντομα": "soon"})
    blocks += rf"""
temporal-adverb(PRED)
IF Ty({backend}:{prop})
   ¬Ex.?x
THEN go(\/1)
   semantic-adverb(PRED)
ELSE abort

temporal-embedded(PRED)
IF Ty({backend}:{prop})
   ¬Ex.?x
   <Y>([+CLAUSE] & [+CLOSED])
THEN go(Y)
   go(\/1)
   semantic-adverb(PRED)
ELSE abort

temporal-local-content(PRED)
IF [+CLAUSE]
   [+CLOSED]
THEN go(\/1)
   semantic-adverb(PRED)
ELSE abort
"""
    rows += [f"{word} {template} {symbol}" for word, symbol in temporal.items()
             for template in ("temporal-adverb", "temporal-embedded", "temporal-local-content")]
    rules = rf"""*causal-clause-closure
IF [+CAUSAL-CONTENT]
   ?[+CLOSED]
   Ty({backend}:{prop})
   ¬?Ty({backend}:{prop})
THEN semantic-close-complement
ELSE abort

*causal-link-completion
IF [+CAUSAL-LINK]
   [+CAUSAL-UPDATE]
   Ty({backend}:{prop})
   ¬Ex.?x
THEN causal-link-close
ELSE abort
"""
    for filename, body in (("lexical-actions.txt", blocks), ("lexicon.txt", "\n".join(rows)), ("computational-actions.txt", rules)):
        path = root / filename
        base = path.read_text().split(MARKER)[0].rstrip()
        path.write_text(base + "\n\n" + MARKER + "\n\n" + body.strip() + "\n")
    path = root / "semantics.json"
    profile = json.loads(path.read_text())
    profile["predicates"].update({r: ["Content", "Content"] for r in RELATIONS})
    profile["clause_relations"] = RELATIONS
    profile.setdefault("modifiers", {}).update({symbol: ["Prop"] for symbol in temporal.values()})
    profile["interpretation_notes"] = [n for n in profile.get("interpretation_notes", [])
                                       if not n.startswith(("because(main, reason)", "Temporal adverbs retain distinct", "Finite clause relations"))]
    profile["interpretation_notes"].append(NOTE)
    profile["interpretation_notes"].append("Finite clause relations preserve distinct causal, temporal, conditional, concessive and contrastive contributions as typed, opaque relations (main, subordinate). Conditional is not material implication; no tense/event calculus, temporal anchoring, counterfactual or concessive inference is supplied. Structural completion does not validate an ambiguous connective's interpretation.")
    temporal_note = "Temporal adverbs retain distinct later/earlier/late/early and deictic operators. Their comparison/reference times and calendar anchoring are contextual; past/present tense inference and full temporal reasoning are not implemented."
    if temporal_note not in profile["interpretation_notes"]:
        profile["interpretation_notes"].append(temporal_note)
    path.write_text(json.dumps(profile, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / "src/dynamicsyntax/grammars"
    for backend in ("classical", "mltt"):
        for language, grammar in (("en", "english"), ("el", "smg")):
            extend(root / f"2026-{grammar}-{backend}", backend, language)
