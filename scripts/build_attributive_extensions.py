"""Maintain noun-relative adjective programs in both native English grammars."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "src/dynamicsyntax/grammars"
MARKER = "// Noun-relative adjectives. Generated by scripts/build_attributive_extensions.py."


def build(backend):
    path = ROOT / f"2026-english-{backend}" / "lexical-actions.txt"
    source = path.read_text().split(MARKER)[0].rstrip()
    blocks = []
    for prefix in ("", "plural-", "contextual-plural-"):
        title = prefix + "adjective"
        start = source.index("\n" + title + "(") + 1
        block = source[start:].split("\n\n")[0]
        block = block.replace(title + "(", prefix + "subsective-adjective(", 1)
        if backend == "mltt":
            block = block.replace("refine(A,PRED)", "refine(A,lam(z,object,PRED(A,z)))")
        else:
            block = block.replace("PRED(x)", "PRED(lam(z,e,cn_body(P(z))),x)")
        blocks.append(block)
    path.write_text(source + "\n\n" + MARKER + "\n\n" + "\n\n".join(blocks) + "\n")


if __name__ == "__main__":
    for backend in ("mltt", "classical"):
        build(backend)
