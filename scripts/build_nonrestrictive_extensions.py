"""Generate the bounded English nonrestrictive LINK family in both native modes."""
from pathlib import Path

MARKER = "// Nonrestrictive relatives. Generated by scripts/build_nonrestrictive_extensions.py."


def extend(root, backend):
    prop = "Prop" if backend == "mltt" else "t"
    blocks = []
    rows = []
    for operation, words in (("open", [","]), ("pronoun", ["who", "which"]),
                             ("close", [","]), ("end", ["."])):
        blocks.append(f"nonrestrictive-{operation}(UNUSED)\nIF Tn(a)\nTHEN nonrestrictive-{operation}\nELSE abort")
        rows.extend(f"{word} nonrestrictive-{operation} none" for word in words)
    # Modifiers can attach before LINK evaluation. Once the conjunction is
    # evaluated, its original VP must not overwrite the supplemental meaning.
    blocks.append(rf"""nonrestrictive-adverb(PRED)
IF Ty({backend}:{prop})
   (?[+APPOS-CLOSED] || ?[+APPOS-EVAL])
THEN go(\/1)
   semantic-adverb(PRED)
ELSE abort""")
    for line in (root / "lexicon.txt").read_text().split(MARKER)[0].splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[1] in {"adverb", "temporal-adverb"}:
            rows.append(f"{fields[0]} nonrestrictive-adverb {fields[2]}")
    rules = rf"""nonrestrictive-evaluation
!completion
IF Tn(0)
   ?[+APPOS-EVAL]
   Ty({backend}:{prop})
THEN nonrestrictive-evaluate
ELSE abort"""
    for filename, body in (("lexical-actions.txt", "\n\n".join(blocks)),
                           ("lexicon.txt", "\n".join(dict.fromkeys(rows))),
                           ("computational-actions.txt", rules)):
        path = root / filename
        path.write_text(path.read_text().split(MARKER)[0].rstrip() + "\n\n" + MARKER + "\n\n" + body + "\n")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / "src/dynamicsyntax/grammars"
    for backend in ("classical", "mltt"):
        extend(root / f"2026-english-{backend}", backend)
